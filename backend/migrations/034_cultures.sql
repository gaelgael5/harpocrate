-- Migration 034 — Cultures (langues ISO 639-1) activables par l'admin
-- (épic docflow « Cultures et templates Listmonk paramétrés en base », feature 1).
--
-- Granularité = langue ISO 639-1 seule, pas de langue-région BCP 47 (décision
-- de cadrage du 2026-11-11) : rien dans Harpocrate ne distingue les régions, et
-- users.preferred_locale comme l'i18n du front ne connaissent que la langue.
--
-- Cette table ne pilote PAS les langues de l'UI ni les valeurs permises de
-- users.preferred_locale (CHECK 'en'/'fr', migration 007) : elle sert aux
-- contenus paramétrés par culture (templates de mails). Élargir l'UI est un
-- sujet séparé.

CREATE TABLE cultures (
    -- Code ISO 639-1 : deux lettres minuscules, rien d'autre (il est repris tel
    -- quel dans les URLs d'admin et comparé à users.preferred_locale).
    code          TEXT         PRIMARY KEY CHECK (code ~ '^[a-z]{2}$'),
    english_name  TEXT         NOT NULL CHECK (char_length(english_name) BETWEEN 1 AND 64),
    -- NULL quand les données CLDR n'ont pas le nom de la langue dans la langue
    -- elle-même : mieux vaut une absence lisible qu'un nom anglais déguisé.
    native_name   TEXT         CHECK (native_name IS NULL OR char_length(native_name) BETWEEN 1 AND 64),
    enabled       BOOLEAN      NOT NULL DEFAULT FALSE,
    -- Culture de repli quand celle d'un utilisateur n'est pas activée ou n'a pas
    -- de contenu : elle doit elle-même être activée, sinon le repli mènerait à
    -- une culture ignorée.
    is_default    BOOLEAN      NOT NULL DEFAULT FALSE,
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT cultures_default_is_enabled CHECK (NOT is_default OR enabled)
);

-- Au plus une culture par défaut : c'est la base qui tranche, pas une lecture
-- préalable côté application (deux admins simultanés passeraient tous deux).
CREATE UNIQUE INDEX cultures_single_default ON cultures (is_default) WHERE is_default;

